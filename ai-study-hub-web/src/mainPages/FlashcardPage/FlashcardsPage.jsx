import { useState, useEffect, useCallback, useMemo, useRef } from "react";
import { useLocation } from "react-router-dom";
import {
  Layers,
  Plus,
  Search,
  BrainCircuit,
  CheckCircle2,
  Award,
  Sparkles,
  BookOpen,
  Clock,
  Pencil,
  Trash2,
  RotateCcw,
  Play,
  MoreVertical,
  Calendar,
  Loader2,
  FileQuestion,
  Filter,
  X,
  AlertCircle,
} from "lucide-react";
import flashcardApi from "../../api/flashcardApi";
import styles from "./FlashcardsPage.module.css";
import FlashcardStudyModal from "./FlashcardStudyModal";
import CreateSetModal from "./CreateSetModal";
import EditSetModal from "./EditSetModal";
import ManageCardsModal from "./ManageCardsModal";

function formatDate(isoString) {
  if (!isoString) return "—";
  const d = new Date(isoString);
  return d.toLocaleDateString("vi-VN", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  });
}

export default function FlashcardsPage() {
  const location = useLocation();
  const [sets, setSets] = useState([]);
  const [isLoading, setIsLoading] = useState(true);
  const [generatingBanner, setGeneratingBanner] = useState(null);
  const hasAutoGenerated = useRef(false);

  // Filters
  const [searchQuery, setSearchQuery] = useState("");
  const [filterStatus, setFilterStatus] = useState("all"); // "all" | "in_progress" | "completed"
  const [sortOrder, setSortOrder] = useState("newest"); // "newest" | "highest_progress" | "most_cards"

  // Active Dropdown state (for 3-dot action menus)
  const [activeDropdownId, setActiveDropdownId] = useState(null);

  // Modals state
  const [isCreateModalOpen, setIsCreateModalOpen] = useState(false);
  const [isEditModalOpen, setIsEditModalOpen] = useState(false);
  const [isManageModalOpen, setIsManageModalOpen] = useState(false);
  const [isStudyModalOpen, setIsStudyModalOpen] = useState(false);
  const [selectedSet, setSelectedSet] = useState(null);

  // 1. Fetch all user flashcard sets
  const fetchSets = useCallback(async () => {
    setIsLoading(true);
    try {
      const data = await flashcardApi.getMySets();
      setSets(Array.isArray(data) ? data : []);
    } catch (err) {
      console.error("Lỗi khi tải danh sách bộ Flashcard:", err);
      setSets([]);
    } finally {
      setIsLoading(false);
    }
  }, []);

  useEffect(() => {
    fetchSets();
  }, [fetchSets]);

  // 1b. Tự động tạo bộ Flashcard bằng AI khi được điều hướng từ tài liệu
  useEffect(() => {
    const doc = location.state?.autoGenerateFromDoc;
    if (!doc || hasAutoGenerated.current) return;
    hasAutoGenerated.current = true;

    // Xóa state điều hướng để tránh bị lặp lại khi người dùng reload trang
    window.history.replaceState({}, document.title);

    const docTitle = doc.title || doc.Title || doc.Filename || "Tài liệu";
    const docId = doc.id || doc.Id;
    const docSummary = doc.summary || doc.Summary || "";

    const autoGenerate = async () => {
      setGeneratingBanner({
        status: "loading",
        title: docTitle,
        message: `Đang phân tích tài liệu "${docTitle}" và tự động tạo các thẻ Flashcard bằng AI...`,
      });

      try {
        // 1. Tạo bộ Flashcard mới với thông tin tài liệu
        const newSet = await flashcardApi.createSet({
          title: docTitle,
          description: `Flashcards của tài liệu: ${docTitle}`,
          documentId: docId || null,
        });

        const newSetId = newSet?.id || newSet?.Id;

        // 2. Gọi API AI để trích xuất & sinh các câu hỏi flashcard
        if (newSetId) {
          try {
            await flashcardApi.generateCardsWithAI(newSetId, docSummary || docTitle);
          } catch (aiErr) {
            console.warn("Lỗi khi sinh thẻ qua AI (vẫn lưu bộ thẻ):", aiErr);
          }
        }

        // 3. Tải lại danh sách bộ Flashcard để hiển thị bộ thẻ vừa tạo
        await fetchSets();

        setGeneratingBanner({
          status: "success",
          title: docTitle,
          message: `Đã tạo thành công bộ Flashcard "${docTitle}" với các thẻ câu hỏi trích xuất từ AI!`,
        });

        // Ẩn thông báo sau 5 giây
        setTimeout(() => {
          setGeneratingBanner(null);
        }, 5000);
      } catch (err) {
        console.error("Lỗi khi tự động tạo bộ Flashcard:", err);
        setGeneratingBanner({
          status: "error",
          title: docTitle,
          message: `Không thể tạo bộ Flashcard: ${err.response?.data?.message || err.message}`,
        });
        setTimeout(() => {
          setGeneratingBanner(null);
        }, 6000);
      }
    };

    autoGenerate();
  }, [location.state, fetchSets]);

  // Close dropdown on click outside
  useEffect(() => {
    const handleDocumentClick = () => setActiveDropdownId(null);
    document.addEventListener("click", handleDocumentClick);
    return () => document.removeEventListener("click", handleDocumentClick);
  }, []);

  // 2. Computed Overall Stats
  const stats = useMemo(() => {
    const totalSets = sets.length;
    let totalCards = 0;
    let totalMastered = 0;

    sets.forEach((s) => {
      totalCards += s.totalCards || s.TotalCards || 0;
      totalMastered += s.masteredCards || s.MasteredCards || 0;
    });

    const averageMastery =
      totalCards === 0 ? 0 : Math.round((totalMastered / totalCards) * 1000) / 10;

    return {
      totalSets,
      totalCards,
      totalMastered,
      averageMastery,
    };
  }, [sets]);

  // 3. Filtered & Sorted Sets
  const filteredSets = useMemo(() => {
    let result = sets.filter((s) => {
      const title = (s.title || s.Title || "").toLowerCase();
      const desc = (s.description || s.Description || "").toLowerCase();
      const q = searchQuery.toLowerCase().trim();

      const matchesQuery = !q || title.includes(q) || desc.includes(q);
      if (!matchesQuery) return false;

      const completion = s.completionPercentage || s.CompletionPercentage || 0;
      if (filterStatus === "completed") return completion === 100;
      if (filterStatus === "in_progress") return completion < 100;
      return true;
    });

    result.sort((a, b) => {
      if (sortOrder === "newest") {
        return new Date(b.createdAt || Date.now()) - new Date(a.createdAt || Date.now());
      }
      if (sortOrder === "highest_progress") {
        return (
          (b.completionPercentage || b.CompletionPercentage || 0) -
          (a.completionPercentage || a.CompletionPercentage || 0)
        );
      }
      if (sortOrder === "most_cards") {
        return (b.totalCards || b.TotalCards || 0) - (a.totalCards || a.TotalCards || 0);
      }
      return 0;
    });

    return result;
  }, [sets, searchQuery, filterStatus, sortOrder]);

  // Actions on Set
  const handleOpenStudy = (set) => {
    setSelectedSet(set);
    setIsStudyModalOpen(true);
  };

  const handleOpenManageCards = (set) => {
    setSelectedSet(set);
    setIsManageModalOpen(true);
  };

  const handleOpenEditSet = (set) => {
    setSelectedSet(set);
    setIsEditModalOpen(true);
  };

  const handleDeleteSet = async (setId, title) => {
    if (!window.confirm(`Bạn có chắc chắn muốn xóa bộ Flashcard "${title}"?`)) return;
    try {
      await flashcardApi.deleteSet(setId);
      fetchSets();
    } catch (err) {
      console.error("Lỗi khi xóa bộ Flashcard:", err);
      alert("Không thể xóa bộ Flashcard. Vui lòng thử lại!");
    }
  };

  const handleResetProgress = async (setId, title) => {
    if (!window.confirm(`Đặt lại toàn bộ tiến độ của bộ thẻ "${title}" về 0% để học lại từ đầu?`))
      return;
    try {
      await flashcardApi.resetProgress(setId);
      fetchSets();
    } catch (err) {
      console.error("Lỗi khi đặt lại tiến độ:", err);
      alert("Không thể đặt lại tiến độ.");
    }
  };

  return (
    <div className={styles.container}>
      {/* ══════════════════════════════════════════════════════════
          1. PAGE HEADER & PRIMARY ACTION
      ══════════════════════════════════════════════════════════ */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="p-1.5 rounded-lg bg-blue-100 text-blue-700">
              <Layers className="w-5 h-5" />
            </span>
            <h1 className="text-2xl font-bold text-slate-900 tracking-tight">
              Bộ thẻ Flashcard
            </h1>
          </div>
          <p className="text-sm text-slate-500">
            Luyện tập và ghi nhớ kiến thức theo phương pháp lặp lại ngắt quãng (Spaced Repetition)
          </p>
        </div>

        <button
          type="button"
          onClick={() => setIsCreateModalOpen(true)}
          className="flex items-center justify-center gap-2 px-4 py-2.5 bg-blue-600 hover:bg-blue-700 text-white text-sm font-semibold rounded-xl shadow-xs hover:shadow transition-all cursor-pointer self-start sm:self-auto"
        >
          <Plus className="w-4 h-4" />
          <span>Tạo bộ thẻ mới</span>
        </button>
      </div>

      {/* ── AI Auto-generate Flashcards Banner ── */}
      {generatingBanner && (
        <div
          className={`flex items-center justify-between p-4 rounded-2xl border transition-all animate-in fade-in slide-in-from-top-2 duration-200 ${
            generatingBanner.status === "loading"
              ? "bg-blue-50/90 border-blue-200 text-blue-900"
              : generatingBanner.status === "success"
              ? "bg-emerald-50/90 border-emerald-200 text-emerald-900"
              : "bg-red-50/90 border-red-200 text-red-900"
          }`}
        >
          <div className="flex items-center gap-3">
            <div
              className={`w-9 h-9 rounded-xl flex items-center justify-center shrink-0 ${
                generatingBanner.status === "loading"
                  ? "bg-blue-100 text-blue-600"
                  : generatingBanner.status === "success"
                  ? "bg-emerald-100 text-emerald-600"
                  : "bg-red-100 text-red-600"
              }`}
            >
              {generatingBanner.status === "loading" ? (
                <Loader2 className="w-5 h-5 animate-spin" />
              ) : generatingBanner.status === "success" ? (
                <Sparkles className="w-5 h-5" />
              ) : (
                <AlertCircle className="w-5 h-5" />
              )}
            </div>
            <div>
              <p className="text-sm font-bold">
                {generatingBanner.status === "loading"
                  ? "Đang tạo Flashcard bằng AI"
                  : generatingBanner.status === "success"
                  ? "Tạo Flashcard AI thành công"
                  : "Lỗi tạo Flashcard"}
              </p>
              <p className="text-xs opacity-90">{generatingBanner.message}</p>
            </div>
          </div>
          {generatingBanner.status !== "loading" && (
            <button
              type="button"
              onClick={() => setGeneratingBanner(null)}
              className="p-1 rounded-lg hover:bg-black/5 transition-colors cursor-pointer text-slate-500"
            >
              <X className="w-4 h-4" />
            </button>
          )}
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════
          2. METRIC & MASTERY STATS OVERVIEW
      ══════════════════════════════════════════════════════════ */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-3 sm:gap-4">
        {/* Stat 1: Total Sets */}
        <div className={styles.statCard}>
          <div className="w-11 h-11 rounded-xl bg-blue-50 text-blue-600 flex items-center justify-center shrink-0">
            <Layers className="w-5 h-5" />
          </div>
          <div>
            <span className="text-xs font-semibold text-slate-500 block">Tổng bộ thẻ</span>
            <span className="text-xl font-bold text-slate-900">{stats.totalSets}</span>
          </div>
        </div>

        {/* Stat 2: Total Cards */}
        <div className={styles.statCard}>
          <div className="w-11 h-11 rounded-xl bg-indigo-50 text-indigo-600 flex items-center justify-center shrink-0">
            <FileQuestion className="w-5 h-5" />
          </div>
          <div>
            <span className="text-xs font-semibold text-slate-500 block">Tổng số câu hỏi</span>
            <span className="text-xl font-bold text-slate-900">{stats.totalCards}</span>
          </div>
        </div>

        {/* Stat 3: Mastered Cards */}
        <div className={styles.statCard}>
          <div className="w-11 h-11 rounded-xl bg-emerald-50 text-emerald-600 flex items-center justify-center shrink-0">
            <CheckCircle2 className="w-5 h-5" />
          </div>
          <div>
            <span className="text-xs font-semibold text-slate-500 block">Đã thuộc lòng</span>
            <span className="text-xl font-bold text-slate-900">{stats.totalMastered}</span>
          </div>
        </div>

        {/* Stat 4: Average Mastery Rate */}
        <div className={styles.statCard}>
          <div className="w-11 h-11 rounded-xl bg-amber-50 text-amber-600 flex items-center justify-center shrink-0">
            <Award className="w-5 h-5" />
          </div>
          <div>
            <span className="text-xs font-semibold text-slate-500 block">Độ thuộc lòng TB</span>
            <span className="text-xl font-bold text-slate-900">
              {stats.averageMastery}%
            </span>
          </div>
        </div>
      </div>

      {/* ══════════════════════════════════════════════════════════
          3. SEARCH, STATUS FILTER & SORT CONTROLS
      ══════════════════════════════════════════════════════════ */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-3 bg-white p-3.5 rounded-2xl border border-slate-200/80 shadow-2xs">
        {/* Search input */}
        <div className="relative flex-1 max-w-md">
          <Search className="w-4 h-4 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Tìm theo tên bộ thẻ hoặc mô tả..."
            className="w-full pl-9 pr-4 py-2 text-xs sm:text-sm bg-slate-50 border border-slate-200 rounded-xl focus:bg-white focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition-all text-slate-800 placeholder:text-slate-400"
          />
        </div>

        <div className="flex flex-wrap items-center gap-2">
          {/* Status Pills */}
          <div className="flex items-center p-1 bg-slate-100 rounded-xl text-xs font-medium text-slate-600">
            <button
              type="button"
              onClick={() => setFilterStatus("all")}
              className={`px-3 py-1.5 rounded-lg transition-all cursor-pointer ${
                filterStatus === "all"
                  ? "bg-white text-blue-600 font-bold shadow-2xs"
                  : "hover:text-slate-900"
              }`}
            >
              Tất cả
            </button>
            <button
              type="button"
              onClick={() => setFilterStatus("in_progress")}
              className={`px-3 py-1.5 rounded-lg transition-all cursor-pointer ${
                filterStatus === "in_progress"
                  ? "bg-white text-blue-600 font-bold shadow-2xs"
                  : "hover:text-slate-900"
              }`}
            >
              Đang học
            </button>
            <button
              type="button"
              onClick={() => setFilterStatus("completed")}
              className={`px-3 py-1.5 rounded-lg transition-all cursor-pointer ${
                filterStatus === "completed"
                  ? "bg-white text-emerald-600 font-bold shadow-2xs"
                  : "hover:text-slate-900"
              }`}
            >
              Đã thuộc 100%
            </button>
          </div>

          {/* Sort Dropdown */}
          <select
            value={sortOrder}
            onChange={(e) => setSortOrder(e.target.value)}
            className="px-3 py-2 text-xs font-semibold bg-slate-50 border border-slate-200 rounded-xl text-slate-700 focus:outline-none focus:bg-white cursor-pointer"
          >
            <option value="newest">Mới nhất</option>
            <option value="highest_progress">% Tiến độ cao nhất</option>
            <option value="most_cards">Nhiều câu hỏi nhất</option>
          </select>
        </div>
      </div>

      {/* ══════════════════════════════════════════════════════════
          4. FLASHCARD SETS GRID
      ══════════════════════════════════════════════════════════ */}
      {isLoading ? (
        <div className="flex flex-col items-center justify-center py-24 gap-3 text-slate-400">
          <Loader2 className="w-8 h-8 animate-spin text-blue-600" />
          <p className="text-sm font-medium">Đang tải danh sách bộ thẻ Flashcard...</p>
        </div>
      ) : filteredSets.length === 0 ? (
        <div className="flex flex-col items-center justify-center py-20 px-4 bg-white rounded-2xl border border-dashed border-slate-300 text-center">
          <div className="w-14 h-14 rounded-2xl bg-blue-50 text-blue-600 flex items-center justify-center mb-3">
            <BrainCircuit className="w-7 h-7" />
          </div>
          <h3 className="text-base font-bold text-slate-800">
            {searchQuery ? "Không tìm thấy bộ Flashcard phù hợp" : "Chưa có bộ Flashcard nào"}
          </h3>
          <p className="text-xs text-slate-500 mt-1 mb-5 max-w-sm">
            {searchQuery
              ? "Hãy thử thay đổi từ khóa tìm kiếm hoặc bỏ bộ lọc trạng thái."
              : "Tạo bộ Flashcard đầu tiên để bắt đầu luyện tập và ghi nhớ bài học dễ dàng hơn!"}
          </p>
          <button
            type="button"
            onClick={() => setIsCreateModalOpen(true)}
            className="flex items-center gap-2 px-4 py-2.5 bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold rounded-xl shadow-xs transition-all cursor-pointer"
          >
            <Plus className="w-4 h-4" />
            <span>Tạo bộ Flashcard mới</span>
          </button>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
          {filteredSets.map((set) => {
            const total = set.totalCards || set.TotalCards || 0;
            const mastered = set.masteredCards || set.MasteredCards || 0;
            const percentage =
              set.completionPercentage !== undefined
                ? set.completionPercentage
                : set.CompletionPercentage !== undefined
                ? set.CompletionPercentage
                : total === 0
                ? 0
                : Math.round((mastered / total) * 100);

            const isDone = percentage === 100 && total > 0;

            return (
              <div
                key={set.id}
                className={`${styles.deckCard} ${
                  isDone ? styles.accentComplete : styles.accentIncomplete
                }`}
              >
                <div>
                  {/* Top Row: Icon + Badge + 3-Dot Actions */}
                  <div className="flex items-start justify-between gap-2 mb-3">
                    <div
                      className={`w-10 h-10 rounded-xl flex items-center justify-center shrink-0 ${
                        isDone
                          ? "bg-emerald-50 text-emerald-600"
                          : "bg-blue-50 text-blue-600"
                      }`}
                    >
                      <BookOpen className="w-5 h-5" />
                    </div>

                    <div className="flex items-center gap-1.5">
                      {isDone ? (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full bg-emerald-50 text-emerald-700 text-[11px] font-bold border border-emerald-200">
                          <CheckCircle2 className="w-3 h-3" /> Đã thuộc 100%
                        </span>
                      ) : (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full bg-blue-50 text-blue-700 text-[11px] font-bold border border-blue-200">
                          Đang học • {percentage}%
                        </span>
                      )}

                      {/* Dropdown Menu */}
                      <div className="relative">
                        <button
                          type="button"
                          onClick={(e) => {
                            e.stopPropagation();
                            setActiveDropdownId((prev) => (prev === set.id ? null : set.id));
                          }}
                          className="p-1 rounded-lg text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors cursor-pointer"
                        >
                          <MoreVertical className="w-4 h-4" />
                        </button>

                        {activeDropdownId === set.id && (
                          <div
                            className="absolute right-0 top-full mt-1 w-44 bg-white rounded-xl shadow-lg border border-slate-100 py-1.5 z-30 animate-in fade-in duration-100"
                            onClick={(e) => e.stopPropagation()}
                          >
                            <button
                              type="button"
                              onClick={() => {
                                setActiveDropdownId(null);
                                handleOpenEditSet(set);
                              }}
                              className="w-full flex items-center gap-2 px-3 py-1.5 text-xs text-slate-700 hover:bg-slate-50 transition-colors cursor-pointer text-left"
                            >
                              <Pencil className="w-3.5 h-3.5 text-slate-400" />
                              <span>Sửa tiêu đề/mô tả</span>
                            </button>

                            <button
                              type="button"
                              onClick={() => {
                                setActiveDropdownId(null);
                                handleResetProgress(set.id, set.title);
                              }}
                              className="w-full flex items-center gap-2 px-3 py-1.5 text-xs text-slate-700 hover:bg-slate-50 transition-colors cursor-pointer text-left"
                            >
                              <RotateCcw className="w-3.5 h-3.5 text-slate-400" />
                              <span>Đặt lại tiến độ (0%)</span>
                            </button>

                            <div className="my-1 border-t border-slate-100" />

                            <button
                              type="button"
                              onClick={() => {
                                setActiveDropdownId(null);
                                handleDeleteSet(set.id, set.title);
                              }}
                              className="w-full flex items-center gap-2 px-3 py-1.5 text-xs text-red-600 hover:bg-red-50 transition-colors cursor-pointer text-left font-medium"
                            >
                              <Trash2 className="w-3.5 h-3.5" />
                              <span>Xóa bộ thẻ</span>
                            </button>
                          </div>
                        )}
                      </div>
                    </div>
                  </div>

                  {/* Title & Description */}
                  <h3 className="text-base font-bold text-slate-900 line-clamp-1 mb-1">
                    {set.title || set.Title}
                  </h3>
                  <p className="text-xs text-slate-500 line-clamp-2 min-h-[2rem] leading-relaxed">
                    {set.description || set.Description || "Chưa có mô tả chi tiết."}
                  </p>

                  {/* Progress & Card Counts */}
                  <div className="mt-4 pt-3 border-t border-slate-100">
                    <div className="flex items-center justify-between text-xs font-semibold text-slate-600 mb-1">
                      <span>Tiến độ thuộc bài</span>
                      <span>
                        {mastered} / {total} thẻ ({percentage}%)
                      </span>
                    </div>

                    <div className={styles.deckProgressTrack}>
                      <div
                        className={styles.deckProgressFill}
                        style={{
                          width: `${percentage}%`,
                          backgroundColor: isDone ? "#10b981" : "#3b82f6",
                        }}
                      />
                    </div>
                  </div>
                </div>

                {/* Bottom Row: Actions */}
                <div className="mt-5 pt-3 border-t border-slate-100 flex items-center gap-2">
                  {/* Study CTA button */}
                  <button
                    type="button"
                    onClick={() => handleOpenStudy(set)}
                    disabled={total === 0}
                    className={`flex-1 flex items-center justify-center gap-1.5 py-2 px-3 rounded-xl text-xs font-bold transition-all cursor-pointer ${
                      total === 0
                        ? "bg-slate-100 text-slate-400 cursor-not-allowed"
                        : "bg-blue-600 hover:bg-blue-700 text-white shadow-xs hover:shadow"
                    }`}
                  >
                    <Play className="w-3.5 h-3.5 fill-current" />
                    <span>Luyện tập ngay</span>
                  </button>

                  {/* Manage Cards button */}
                  <button
                    type="button"
                    onClick={() => handleOpenManageCards(set)}
                    className="py-2 px-3 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold transition-colors cursor-pointer"
                  >
                    Quản lý thẻ ({total})
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════
          5. MODALS INTEGRATION
      ══════════════════════════════════════════════════════════ */}
      {/* Interactive 3D Flip Card Study Modal */}
      <FlashcardStudyModal
        isOpen={isStudyModalOpen}
        onClose={() => {
          setIsStudyModalOpen(false);
          fetchSets();
        }}
        flashcardSet={selectedSet}
        onProgressUpdated={() => fetchSets()}
      />

      {/* Create Set Modal */}
      <CreateSetModal
        isOpen={isCreateModalOpen}
        onClose={() => setIsCreateModalOpen(false)}
        onSuccess={() => fetchSets()}
      />

      {/* Edit Set Modal */}
      <EditSetModal
        isOpen={isEditModalOpen}
        onClose={() => {
          setIsEditModalOpen(false);
          setSelectedSet(null);
        }}
        flashcardSet={selectedSet}
        onSuccess={() => fetchSets()}
      />

      {/* Manage Cards in Set Modal */}
      <ManageCardsModal
        isOpen={isManageModalOpen}
        onClose={() => {
          setIsManageModalOpen(false);
          setSelectedSet(null);
          fetchSets();
        }}
        flashcardSet={selectedSet}
        onCardsUpdated={() => fetchSets()}
      />
    </div>
  );
}
